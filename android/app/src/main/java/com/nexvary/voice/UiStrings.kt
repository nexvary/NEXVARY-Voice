    fun render(value:String,context:Context):String {
        entries[value]?.let { return context.getString(it) }
        // Preserve appended numbers, file names and server error details.
        entries.entries.filter { it.key.endsWith(": ") || it.key=="صوت اللغة " || it.key=="تعذر التعرف على الصوت (رمز " }.sortedByDescending { it.key.length }.firstOrNull { value.startsWith(it.key) }?.let {
            return context.getString(it.value)+render(value.substring(it.key.length),context)
        }
        entries.entries.firstOrNull { it.key.startsWith(" ") && value.endsWith(it.key) }?.let {
            return value.dropLast(it.key.length)+context.getString(it.value)
        }
        return value
    }
